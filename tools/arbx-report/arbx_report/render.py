"""report.json (machine) and report.md (human). Deterministic: sorted keys, no wall-clock time, inputs by sha256."""
from __future__ import annotations

import json
import os

TOOL_VERSION = "arbx-report/0.1"


def normalize(obj):
    """Floats to 9 significant digits, so a last-ulp difference of a libm function between machines does not change
    report.json (the golden test compares bytes)."""
    if isinstance(obj, float):
        v = float(f"{obj:.9g}")
        return int(v) if v.is_integer() and abs(v) < 2 ** 53 else v
    if isinstance(obj, dict):
        return {k: normalize(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [normalize(v) for v in obj]
    return obj


def dumps(obj) -> str:
    return json.dumps(normalize(obj), sort_keys=True, indent=1, ensure_ascii=False, allow_nan=False) + "\n"


def write_atomic(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, path)


def write_jsonl(path: str, rows: list) -> None:
    write_atomic(path, "".join(json.dumps(r, sort_keys=True, ensure_ascii=False) + "\n" for r in rows))


def _fmt(v) -> str:
    if isinstance(v, bool) or v is None:
        return str(v).lower() if isinstance(v, bool) else "-"
    if isinstance(v, int):
        return f"{v:,}"
    if isinstance(v, float):
        return f"{v:,.4g}" if abs(v) < 1e6 else f"{v:,.0f}"
    if isinstance(v, (list, dict)):
        s = json.dumps(v, sort_keys=True, ensure_ascii=False)
        return s if len(s) <= 160 else s[:157] + "..."
    return str(v)


def _md_obj(obj, depth: int, out: list) -> None:
    if isinstance(obj, dict):
        flat = {k: v for k, v in obj.items() if not isinstance(v, (dict, list)) or len(json.dumps(v)) <= 160}
        nested = {k: v for k, v in obj.items() if k not in flat}
        if flat:
            out.append("| key | value |")
            out.append("|---|---|")
            for k, v in flat.items():
                out.append(f"| {k} | {_fmt(v)} |")
            out.append("")
        for k, v in nested.items():
            if depth >= 4:
                out.append(f"- **{k}**: {_fmt(v)}")
                continue
            out.append(f"{'#' * min(6, depth + 3)} {k}")
            out.append("")
            _md_obj(v, depth + 1, out)
    elif isinstance(obj, list):
        if obj and all(isinstance(x, dict) for x in obj) and len(obj) <= 60:
            keys = []
            for x in obj:
                for k in x:
                    if k not in keys and not isinstance(x[k], (dict, list)):
                        keys.append(k)
            keys = keys[:10]
            if keys:
                out.append("| " + " | ".join(keys) + " |")
                out.append("|" + "---|" * len(keys))
                for x in obj:
                    out.append("| " + " | ".join(_fmt(x.get(k)) for k in keys) + " |")
                out.append("")
                return
        out.append(f"{_fmt(obj)}")
        out.append("")
    else:
        out.append(_fmt(obj))
        out.append("")


def markdown(report: dict) -> str:
    out = [f"# {report.get('kind', 'segment')} report: {report.get('name')}", ""]
    out.append(f"Generated by {report.get('tool')} from the recorded files alone. Inputs are listed with their sha256 at the end.")
    out.append("")
    w = report.get("window") or {}
    if w:
        out.append(f"Wall hours: {_fmt(w.get('wall_hours'))} (end from {w.get('end_src')}); trading hours: "
                   f"{_fmt(w.get('trading_hours'))}.")
        out.append("")
    for sec in report.get("sections") or []:
        out.append(f"## {sec['id']} {sec['title']}")
        out.append("")
        if not sec.get("complete", True):
            out.append("**Incomplete:** " + "; ".join(sec.get("incomplete") or []))
            out.append("")
        for c in sec.get("caveats") or []:
            out.append(f"> {c}")
        if sec.get("caveats"):
            out.append("")
        _md_obj({k: v for k, v in (sec.get("data") or {}).items() if k != "rows"}, 0, out)
    if report.get("inputs"):
        out.append("## Inputs")
        out.append("")
        out.append("| file | bytes | schema | sha256 |")
        out.append("|---|---|---|---|")
        for i in report["inputs"]:
            out.append(f"| {i.get('segment', '') + '/' if i.get('segment') else ''}{i['file']} | {_fmt(i.get('bytes'))} | "
                       f"{i.get('schema') or '-'} | {(i.get('sha256') or '')[:16]} |")
        out.append("")
    return "\n".join(out)


def write_report(out_dir: str, report: dict, name: str = "report") -> tuple[str, str]:
    pj = os.path.join(out_dir, f"{name}.json")
    pm = os.path.join(out_dir, f"{name}.md")
    write_atomic(pj, dumps(report))
    write_atomic(pm, markdown(report))
    return pj, pm
