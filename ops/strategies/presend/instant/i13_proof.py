#!/usr/bin/env python3
# INSTANT-BOTS study, step 13 (read-only, local + cached Jito answers): proof examples per bot class -> markdown rows with solscan
# links (dump tx, instant buy tx, attempts right before for pre-senders, Jito bundle id when the dump and the buy share one).
# usage: python3 -I i13_proof.py CLASSES.json WIN.jsonl.gz JITO_SAMPLE.json PROBE_JITO.json OUT.md
import sys, json, gzip, collections
C = json.load(open(sys.argv[1])); winp = sys.argv[2]; js = json.load(open(sys.argv[3])); pj = json.load(open(sys.argv[4])); outp = sys.argv[5]
W = collections.defaultdict(list)
for l in gzip.open(winp, "rt"):
    r = json.loads(l); W[(r[0], r[1])].append(r)
tx = lambda s: f"[{s[:6]}…](https://solscan.io/tx/{s})"
acct = lambda a: f"[{a[:8]}](https://solscan.io/account/{a})"
def fam969(r): return r["cup"] == 500 and r["cul"] == 200000 and not r["tsv"]
L = []
L.append("# Proof examples (solscan links; generated by i13_proof.py)")
L.append("Format: bot (class) · slot / leader · dump → instant buy (+block positions) · evidence.")
def attempts(r, n=2):
    rows = [x for s in range(r["s"] - 3, r["s"] + 1) for x in W.get((r["mint"], s), [])]
    sg = set(r["signers"])
    a = sorted([x for x in rows if set(x[4]) & sg and (x[5] is not None or not x[12]) and (x[1], x[2]) < (r["s"], r["di"])], key=lambda x: (x[1], x[2]))
    return a, a[-n:]
PRE = ["CZ77onJz", "9K5QgBKa", "Dk2jdQ93", "FUru6V3L", "5ZKd8DNB", "2KtcBCfh", "FNuoWSQc", "2XyiEK56"]
for k in PRE:
    ev = sorted([r for r in C if r["u"].startswith(k) and r["cls"] == "P"], key=lambda r: (r["gap"], -r["own_before"]))
    for r in ev[:2]:
        allatt, last = attempts(r)
        ev_s = f"{len(allatt)} own attempts on this token in the 3 slots before + the dump slot ({collections.Counter(x[5] or 'no-op' for x in allatt).most_common(2)}); last ones: " + ", ".join(
            f"{tx(x[3])} (s{x[1] - r['s']:+d} i{x[2]}, {x[5] or 'no-op'})" for x in last)
        L.append(f"- {acct(r['u'])} (H1 pre-sender) · {r['s']} / {r['client']} · dump {tx(r['dsig'])} by {r['dumper'][:8]} {r['dsol'] / 1e9:.2f} SOL −{100 * r['drop']:.0f}% → buy {tx(r['sig'])} (+{r['gap']}) · {ev_s}")
same = [x for x in js if x["same"]]
for lab in ("rotation-969 jito", "rotation-969 bam", "rotation-969 harmonic", "B same-prog jito/bam", "R gap1-5 other jito/bam"):
    for x in [x for x in same if x["stratum"] == lab][:2]:
        b = x["buy_bundle"]
        L.append(f"- {acct(x['u'])} ({'seller-own bundle' if lab.startswith(('rotation', 'B')) else 'bundled with the dump'}; {lab}) · {x['s']} / {x['client']} · dump {tx(x['dsig'])} by {x['dumper'][:8]} → buy {tx(x['sig'])} (+{x['gap']}) · "
                 f"SAME Jito bundle [{b['bundle_id'][:10]}…](https://explorer.jito.wtf/bundle/{b['bundle_id']}) ({len(b.get('txs') or [])} txs, tip {b.get('tip')} paid by {', '.join(t[:8] for t in b.get('tippers') or [])})")
for k in ["HkQ7hMjy", "haqqiUUX", "DF7eRXHn", "GKd5EMzR"]:
    ev = [r for r in C if r["u"].startswith(k) and 21 <= r["gap"] <= 40 and r["cls"] == "R"]
    for r in ev[:1]:
        L.append(f"- {acct(r['u'])} (reactive H5, 20+ positions) · {r['s']} / {r['client']} · dump {tx(r['dsig'])} by {r['dumper'][:8]} {r['dsol'] / 1e9:.2f} SOL → buy {tx(r['sig'])} (+{r['gap']}) · no own attempts before")
for x in pj:
    L.append(f"- {acct(x['buy_user'])} (probe instant buy) · {x['slot']} / {x['client']} · dump {tx(x['dump_sig'])} by {x['dump_user'][:8]} → buy {tx(x['buy_sig'])} (+{x['gap']}) · "
             f"{'SAME Jito bundle ' + x['buy_bundle']['bundle_id'][:10] if x['same_bundle'] else 'not in the dump’s Jito bundle'}")
open(outp, "w").write("\n".join(L) + "\n")
print(len(L) - 2, "lines")
