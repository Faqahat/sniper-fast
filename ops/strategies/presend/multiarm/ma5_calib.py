REFUND = 1508820
FAIL = 5120

_orig_stop = L.stop_times


def stop_times(P, cfg, R):
    if getattr(P, "re_stop", None) is not None: return P.re_stop, P.re_en
    return _orig_stop(P, cfg, R)


L.stop_times = stop_times


def live_cash(W):
    fails = sum(1 for a in W["tries"] if a["land"] and a["land"].get("res") not in (None, "unseen", "ok"))
    real = sum((x["pnl"] or 0) for x in W["real"]) / 1e9
    nf = 1 if W["fills"] else 0
    return real + nf * REFUND / 1e9 - fails * FAIL / 1e9, real, fails, nf


def main(ctxp, outp, reps=8):
    Wd = S.World(ctxp)
    X = Wd.X; R = Wd.R; tape = Wd.tape; cal = Wd.cal
    R.kratio = 1.0
    out = {"run": Wd.run, "span_h": (Wd.t_end - Wd.t_start) / 3.6e6}
    # live windows inside the span
    live = []
    for W in X["wins"]:
        t_arm = W["rearm"]["arm_t"] / 1e6 if W["kind"] == "rearm" else W["trig"]["t"] / 1e6
        if not (Wd.t_start <= t_arm <= Wd.t_end) or W["en_slot"] > cal["s_end"]: continue
        P = prep_live(tape, W)
        if P is None: continue
        P.live_exit_slots = 2; P.live_exit_ms = 200
        live.append((W, P))
    agg = collections.defaultdict(lambda: collections.defaultdict(float))
    for W, P in live:
        c, real, fails, nf = live_cash(W)
        a = agg[W["kind"]]; a["windows"] += 1; a["fills"] += nf; a["realized"] += real; a["cash"] += c; a["fail_tries"] += fails
    out["live"] = {k: dict(v) for k, v in agg.items()}
    # A. real tries
    A = collections.defaultdict(lambda: collections.defaultdict(float))
    for W, P in live:
        size = (W.get("spend") or 696_000_000) / 1e9
        cfg = dict(Wd.cfg_t2 if W["kind"] == "t2" else Wd.cfg_re, size=size)
        # the live stop for both kinds (real tries only: no phantom period)
        P.re_stop = W["dis"]["t"] / 1e6 if W["dis"] and W["dis"].get("t") else (P.tries[-1]["t"] + 1 if P.tries else None)
        P.re_en = W["en_slot"]
        if P.re_stop is None: continue
        rng = np.random.default_rng(1)
        r = L.window_sim(P, cfg, R, rng, (), ())
        a = A[W["kind"]]
        a["sim_fills"] += r["filled"]; a["same_try"] += bool(r.get("live_try"))
        if r["filled"]: a["sim_realized"] += (r["pnl"] + r["fails"] * L.FAIL - (L.FIX_REAL - L.FIX)) / 1e9
        a["sim_fail_tries"] += r["fails"]
        P.re_stop = None
    out["A_real_tries"] = {k: dict(v) for k, v in A.items()}
    # B. phantom tries on the live windows (one window at a time: no caps, no pauses)
    B = collections.defaultdict(lambda: collections.defaultdict(list))
    for rep in range(reps):
        tot = collections.defaultdict(lambda: collections.defaultdict(float))
        for W, P in live:
            kind = W["kind"]
            size = 0.65 if kind == "rearm" else Wd.cfg_t2["size"]
            Wd.anchor(P)
            if kind == "rearm":
                t0 = W["rearm"]["arm_t"] / 1e6 + cal["first_re"]
                if W["dis"] and W["dis"]["why"] not in ("filled",) and W["dis"].get("t"): t_stop = W["dis"]["t"] / 1e6
                else:
                    tl = tape.tok(W["mint"])
                    re = W["rearm"]
                    k_from = None
                    if re.get("deferred"): k_from = next((k for k in range(tl.n) if Wd.seen(tl, k) >= re["arm_t"] / 1e6), tl.n)
                    t_stop, why, _ = M.natural_end(tape, tl, M.Rule("R0"), Wd.A, re["arm_t"] / 1e6, re.get("arm_slot") or re["check_slot"], W["en_slot"], k_from)
                    t_stop += cal["end_dt"].get(why, 0.0)
                en = W["en_slot"]
            else:
                t0 = P.t_trig + cal["first_t2"]
                t_stop, en = _orig_stop(P, Wd.cfg_t2, R)
            r = one_window(Wd, P, kind, size, t0, t_stop, en, rep)
            T = tot[kind]
            T["fills"] += r["filled"]; T["cash_raw"] += r["cash_raw"]; T["cash_slip"] += r["cash_slip"]; T["cash_cut"] += r["cash_cut"]; T["fails"] += r["fails"]
            if W["fills"]: T["fills_on_live_filled"] += r["filled"]
            else: T["fills_on_live_unfilled"] += r["filled"]
        for k, v in tot.items():
            for kk, vv in v.items(): B[k][kk].append(vv)
    out["B_phantom_live_windows"] = {k: {kk: [round(float(np.mean(vv)), 4), round(float(np.min(vv)), 4), round(float(np.max(vv)), 4)] for kk, vv in v.items()} for k, v in B.items()}
    # C. the joint replay of R0 (and C0: T2 alone, no re-arm)
    for nm, rule in (("C0_joint_T2only", None), ("C_joint_R0", M.Rule("R0"))):
        C = joint(Wd, rule, reps, out, nm)
        out[nm] = {k: {kk: [round(float(np.mean(vv)), 4), round(float(np.min(vv)), 4), round(float(np.max(vv)), 4)] for kk, vv in v.items()} for k, v in C.items()}
    json.dump(out, open(outp, "w"), indent=1, default=str)
    print(json.dumps(out, indent=1, default=str))


def joint(Wd, rule, reps, out, nm):
    C = collections.defaultdict(lambda: collections.defaultdict(list))
    for rep in range(reps):
        res, meta = S.simulate(Wd, rule, rep)
        tot = collections.defaultdict(lambda: collections.defaultdict(float))
        for r in res:
            T = tot[r["kind"]]; T["windows"] += 1; T["fills"] += r["filled"]; T["cash_raw"] += r["cash_naive"]; T["cash_slip"] += r["cash"]; T["cash_cut"] += r["cash_cut"]
            T["fails"] += r["fails"]
        for k, v in tot.items():
            for kk, vv in v.items(): C[k][kk].append(vv)
        if rep == 0: out[nm + "_meta_rep0"] = meta
    return C


def one_window(Wd, P, kind, size, t0, t_stop, en, rep):
    """phantom ticks of one window alone (no caps / pauses): fill, exit, cash raw / slip / cut"""
    R = Wd.R; iv = Wd.cal["iv"]
    rng = S.rng_for(rep, "calB", Wd.run, P.W["w"])
    best = None; landed = 0; t = t0
    while t < t_stop:
        if best is not None and t >= best[1] + P.off: break
        slot = int((t - P.off_s) // M.SMS)
        if slot > en: break
        dl = min(slot + 1, en)
        if rng.random() >= R.p_unseen:
            V, T, _ = L.state_at_c(P, t - P.off)
            c = t - P.off + max(5.0, float(R.L[rng.integers(len(R.L))]))
            s, i = P.pos_of(c); landed += 1
            if s <= dl and V < M.UNTRADE_V:
                mo, _ = L.limit_min_out(V, T, int(round(size * 1e9)), L.FR, 0.12)
                V2, T2, kn = L.state_before(P, s, i)
                tok, xn = L.buy_out(V2, T2, int(round(size * 1e9)))
                if tok >= mo and (best is None or (s, i) < best[0]): best = ((s, i), c, kn, V2, T2, tok, xn)
        t += iv
    if best is None: return {"filled": False, "cash_raw": -landed * FAIL / 1e9, "cash_slip": -landed * FAIL / 1e9, "cash_cut": -landed * FAIL / 1e9, "fails": landed}
    (fs, fi), c, kn, Vb, Tb, tok, xn = best
    fails = landed - 1
    tf = c + P.off
    Dw = float(R.D[rng.integers(len(R.D))])
    cfg = Wd.cfg_t2 if kind == "t2" else Wd.cfg_re
    ex = L.exit_walk(P, kn, Tb, tok, int(round(size * 1e9)), tf, Dw, R.tau, cfg, R, rng, False, fs)
    raw = ex["gross"] / 1e9 - size - L.FIX / 1e9 - fails * FAIL / 1e9
    recs = Wd.recs(P.mint); mi = PA.last_before(recs, (fs, fi, -1)) if recs else None
    ds = dc = 0.0
    if mi is not None:
        vn = PA.value_at(recs, mi, size, False, ex["c_sell"], Wd.tape.maxi, by_cc=True)
        vs = PA.value_at(recs, mi, size, True, ex["c_sell"], Wd.tape.maxi, by_cc=True)
        vc = S.value_cut(recs, mi, size, ex["c_sell"], Wd.tape.maxi, 0.2, S.rng_for(rep, "cutB", Wd.run, P.W["w"]))
        if vn and vs and vc is not None: ds = vs["gross"] - vn["gross"]; dc = vc - vn["gross"]
    return {"filled": True, "cash_raw": raw, "cash_slip": raw + ds, "cash_cut": raw + dc, "fails": fails}


