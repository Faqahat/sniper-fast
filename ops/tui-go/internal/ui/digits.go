var digitsASC = map[rune][3]string{
	'0': {" _ ", "| |", "|_|"}, '1': {"   ", "  |", "  |"}, '2': {" _ ", " _|", "|_ "}, '3': {" _ ", " _|", " _|"},
	'4': {"   ", "|_|", "  |"}, '5': {" _ ", "|_ ", " _|"}, '6': {" _ ", "|_ ", "|_|"}, '7': {" _ ", "  |", "  |"},
	'8': {" _ ", "|_|", "|_|"}, '9': {" _ ", "|_|", " _|"}, '.': {" ", " ", "."}, '+': {"   ", "_|_", " | "},
	'-': {"   ", " _ ", "   "}, '$': {" _ ", "(_ ", " _)"}, ',': {" ", " ", ","},
}

// bigText renders s in big numerals: rows 2, 3 or 5 (ascii: always the 3-row seven-segment face).
func bigText(s string, rows int, ascii bool) []string {
	if ascii {
		rows = 3
	}
	out := make([]string, rows)
	rs := []rune(s)
	for i, ch := range rs {
		sep := i < len(rs)-1
		switch {
		case ascii:
			g, ok := digitsASC[ch]
			if !ok {
				continue
			}
			for r := 0; r < 3; r++ {
				out[r] += g[r]
				if sep {
					out[r] += " "
				}
			}
		case rows == 2:
			g, ok := digits2[ch]
			if !ok {
				continue
			}
			for r := 0; r < 2; r++ {
				out[r] += g[r]
				if sep {
					out[r] += " "
				}
			}
		case rows == 5:
			g, ok := bitmap5[ch]
			if !ok {
				continue
			}
			for r := 0; r < 5; r++ {
				var b strings.Builder
				for _, px := range g[r] {
					if px == '1' {
						b.WriteString("██")
					} else {
						b.WriteString("  ")
					}
				}
				out[r] += b.String()
				if sep {
					out[r] += " "
				}
			}
		default:
			g, ok := digits3[ch]
			if !ok {
				continue
			}
			for r := 0; r < 3; r++ {
				out[r] += g[r]
				if sep {
					out[r] += " "
				}
			}
		}
	}
	return out
}
