#!/usr/bin/env python3
# LANDING-PATH STUDY, step 6: assemble LANDING_PATHS.md from the narrative template + generated tables.
# usage: python3 -I l6_assemble.py
import os
D = "/home/moiz/sniper/ops/overnight/landing"; W = os.path.join(D, "work")
s = open(os.path.join(W, "LANDING_PATHS.tmpl.md")).read()
for k in ["S1", "S2", "S3", "S4", "S5"]:
    s = s.replace("{{" + k + "}}", open(os.path.join(W, f"summary_{k}.md")).read().strip())
tables = open(os.path.join(W, "tables.md")).read().replace("## Tables (generated by l4_report.py)", "").strip()
s = s.replace("{{TABLES}}", tables)
open(os.path.join(D, "LANDING_PATHS.md"), "w").write(s)
print("wrote", os.path.join(D, "LANDING_PATHS.md"), len(s), "chars")
