#!/usr/bin/env python3
"""make_race_toml.py — build the feed-race config for the Shreder trial from the ENGINE's own config (server side).

Runs on FRA as root (deployed to /root/shreder/ck/). Reads the engine's current [[feed]] blocks (default
/root/prod/dip_prod.toml, fallback /root/sniper-dip/dip_probe.toml) and writes OUT (chmod 600) with only the
Constant-K feeds the engines use now (default: kaldera, turbo-kaldera, kaldera-tx), each with the engine's exact
url / token_env / token_header, account_include = the pump.fun program only (the harness logs pump txs only), and
env_file = /root/sniper/deploy/.env (the engines' token source).

NEVER prints URLs or tokens: only feed names, kinds, the token_env NAMES, whether each token name is present in the
env file (count), and an 8-hex sha256 of each URL (to tell "same endpoint as the engine" without revealing it).

usage: python3 make_race_toml.py OUT.toml [--feeds kaldera,turbo-kaldera,kaldera-tx] [--src FILE]
"""
import hashlib
import os
import sys
import tomllib

PUMP = "6EF8rrecthR5Dkzon8Nwu78hRvfCKubJ14M5uBEwF6P"
ENV_FILE = os.environ.get("CK_ENV_FILE", "/root/sniper/deploy/.env")
SRCS = [os.environ["CK_ENGINE_CFG"]] if os.environ.get("CK_ENGINE_CFG") else ["/root/prod/dip_prod.toml", "/root/sniper-dip/dip_probe.toml"]
OK_KINDS = {"yellowstone-deshred", "yellowstone-tx", "jito-entries"}


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    a = sys.argv[1:]
    if not a or a[0].startswith("-"):
        sys.exit(__doc__)
    out = a[0]
    want = ["kaldera", "turbo-kaldera", "kaldera-tx"]
    srcs = SRCS
    i = 1
    while i < len(a):
        if a[i] == "--feeds":
            want = [x for x in a[i + 1].split(",") if x]; i += 2
        elif a[i] == "--src":
            srcs = [a[i + 1]]; i += 2
        else:
            sys.exit(f"unknown arg {a[i]}")
    src = next((p for p in srcs if os.path.exists(p)), None)
    if not src:
        sys.exit(f"REFUSED: no engine config found ({', '.join(srcs)})")
    cfg = tomllib.load(open(src, "rb"))
    feeds = {f.get("name"): f for f in cfg.get("feed", [])}
    env_names = set()
    if os.path.exists(ENV_FILE):
        for line in open(ENV_FILE, errors="replace"):
            line = line.strip()
            if line.startswith("export "):
                line = line[7:]
            if "=" in line and not line.startswith("#"):
                env_names.add(line.split("=", 1)[0].strip())
    blocks, notes = [], []
    for n in want:
        f = feeds.get(n)
        if f is None:
            sys.exit(f"REFUSED: feed {n!r} not in {src} (has: {', '.join(k for k in feeds if k)})")
        kind = f.get("kind")
        if kind not in OK_KINDS:
            sys.exit(f"REFUSED: feed {n!r} kind {kind!r} is not a harness gRPC kind ({', '.join(sorted(OK_KINDS))})")
        url = f.get("url")
        if not url:
            sys.exit(f"REFUSED: feed {n!r} has no url")
        te = f.get("token_env")
        if te and te not in env_names:
            sys.exit(f"REFUSED: feed {n!r} token_env {te} is not in {ENV_FILE}")
        b = ["[[feed]]", f"name = {q(n)}", f"kind = {q(kind)}", f"url = {q(url)}"]
        if te:
            b.append(f"token_env = {q(te)}")
        if f.get("token_header"):
            b.append(f"token_header = {q(f['token_header'])}")
        if kind != "jito-entries":
            b.append(f"account_include = [{q(PUMP)}]")
        blocks.append("\n".join(b))
        notes.append(f"{n} kind={kind} token_env={te or '-'} url_sha={hashlib.sha256(url.encode()).hexdigest()[:8]} "
                     f"engine_enabled={f.get('enabled', True)}")
    body = (f"# generated by make_race_toml.py from {src} (engine config, read-only); never print this file\n"
            f"env_file = {q(ENV_FILE)}\n\n" + "\n\n".join(blocks) + "\n")
    tmp = out + ".tmp"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as w:
        w.write(body)
    os.replace(tmp, out)
    os.chmod(out, 0o600)
    print(f"race config: {out} from {src}")
    for x in notes:
        print("  feed", x)


if __name__ == "__main__":
    main()
